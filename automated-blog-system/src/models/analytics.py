# Blueprint Proposals
# ---------------------------------------------------------------------------


class BlueprintProposal(db.Model):
    """A proposed update to one field in a Blueprint.

    Generated by the feedback engine after analysing per-Blueprint-version
    performance distributions. Never auto-applied: a human must accept or
    reject via the ``/api/proposals/<id>/accept|reject`` routes.

    On accept: a new Blueprint version is created via the PR #5a machinery.
    On reject: the row is closed and the current Blueprint is unchanged.
    """

    __tablename__ = "blueprint_proposals"

    id = Column(Integer, primary_key=True)
    niche_id = Column(Integer, ForeignKey("niches.id"), nullable=True, index=True)
    blueprint_id = Column(String(64), nullable=False)
    blueprint_field = Column(String(80), nullable=False)  # e.g. 'word_count_range'
    current_value_json = Column(Text, nullable=False)     # JSON-serialised current value
    proposed_value_json = Column(Text, nullable=False)    # JSON-serialised proposed value
    evidence_json = Column(Text, nullable=False)          # sample size, effect size, CI, articles
    generated_at = Column(DateTime, default=datetime.utcnow, nullable=False)
    status = Column(String(20), default="pending", nullable=False)  # pending|accepted|rejected
    reviewed_by = Column(String(100), nullable=True)
    reviewed_at = Column(DateTime, nullable=True)

    # FK to the newly-created Blueprint version after accept; null until then.
    resulting_blueprint_id = Column(String(64), nullable=True)

    def current_value(self) -> Any:
        try:
            return json.loads(self.current_value_json)
        except (TypeError, ValueError):
            return self.current_value_json

    def proposed_value(self) -> Any:
        try:
            return json.loads(self.proposed_value_json)
        except (TypeError, ValueError):
            return self.proposed_value_json

    def evidence(self) -> Dict[str, Any]:
        try:
            return json.loads(self.evidence_json or "{}")
        except (TypeError, ValueError):
            return {}

    def to_dict(self) -> Dict[str, Any]:
        return {
            "id": self.id,
            "niche_id": self.niche_id,
            "blueprint_id": self.blueprint_id,
            "blueprint_field": self.blueprint_field,
            "current_value": self.current_value(),
            "proposed_value": self.proposed_value(),
            "evidence": self.evidence(),
            "generated_at": self.generated_at.isoformat() if self.generated_at else None,
            "status": self.status,
            "reviewed_by": self.reviewed_by,
            "reviewed_at": self.reviewed_at.isoformat() if self.reviewed_at else None,
            "resulting_blueprint_id": self.resulting_blueprint_id,
        }


# ---------------------------------------------------------------------------
# Article Improvement Proposals (retroactive editing)
# ---------------------------------------------------------------------------


class ArticleImprovementProposal(db.Model):
    """Per-article suggestion derived from the active Blueprint.

    When a BlueprintProposal is accepted (or on-demand via
    ``generate_improvement_proposals``), the feedback engine scans
    published articles in the same niche, identifies non-conformant
    high-confidence fields, and creates one row per gap.

    The human reviews these in the ArticleReview UI. On **Apply**, the
    proposal is marked complete and Ghost-backed articles are flagged with
    ``has_unpushed_changes`` so an editor can make the recommended content
    change manually. On **Dismiss**, the row is closed with an optional reason.
    A database uniqueness constraint on ``(article_id, blueprint_field, status)``
    prevents duplicate pending proposals for the same field while still
    preserving applied/dismissed history.
    """

    __tablename__ = "article_improvement_proposals"
    __table_args__ = (
        UniqueConstraint(
            "article_id",
            "blueprint_field",
            "status",
            name="uq_improvement_proposals_article_field_status",
        ),
    )

    id = Column(Integer, primary_key=True)
    article_id = Column(Integer, ForeignKey("articles.id"), nullable=False, index=True)
    # Optional back-link to the blueprint proposal that triggered generation.
    blueprint_proposal_id = Column(Integer, ForeignKey("blueprint_proposals.id"), nullable=True)
    blueprint_field = Column(String(80), nullable=False)
    current_value_json = Column(Text, nullable=False)    # what the article currently has
    recommended_value_json = Column(Text, nullable=False) # what it should have
    rationale = Column(Text, nullable=True)
    evidence_json = Column(Text, nullable=True)
    status = Column(String(20), default="pending", nullable=False)  # pending|applied|dismissed
    dismissed_reason = Column(Text, nullable=True)
    generated_at = Column(DateTime, default=datetime.utcnow, nullable=False)
    reviewed_at = Column(DateTime, nullable=True)

    def current_value(self) -> Any:
        try:
            return json.loads(self.current_value_json)
        except (TypeError, ValueError):
            return self.current_value_json

    def recommended_value(self) -> Any:
        try:
            return json.loads(self.recommended_value_json)
        except (TypeError, ValueError):
            return self.recommended_value_json

    def evidence(self) -> Dict[str, Any]:
        try:
            return json.loads(self.evidence_json or "{}")
        except (TypeError, ValueError):
            return {}

    def to_dict(self) -> Dict[str, Any]:
        return {
            "id": self.id,
            "article_id": self.article_id,
            "blueprint_proposal_id": self.blueprint_proposal_id,
            "blueprint_field": self.blueprint_field,
            "current_value": self.current_value(),
            "recommended_value": self.recommended_value(),
            "rationale": self.rationale,
            "evidence": self.evidence(),
            "status": self.status,
            "dismissed_reason": self.dismissed_reason,
            "generated_at": self.generated_at.isoformat() if self.generated_at else None,
            "reviewed_at": self.reviewed_at.isoformat() if self.reviewed_at else None,
        }


